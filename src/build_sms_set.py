# ────────────────────────────────────────────── 결합 표본 — 세션 재판정용 입력 형식

def joined(a_channel, a, b_channel, b):
    return f"[{a_channel}] {a}\n[{b_channel}] {b}"


def fill(template, rng):
    n = str(rng.randint(10000, 99999))
    return template.format(
        org=rng.choice(ORG), bank=rng.choice(BANK), card=rng.choice(CARD), courier=rng.choice(COURIER),
        shop=rng.choice(SHOP), name=rng.choice(NAME), fam=rng.choice(FAMILY), bad=rng.choice(BAD_LINK),
        good=rng.choice(GOOD_LINK), amt=rng.choice(AMT), time=rng.choice(TIME), place=rng.choice(PLACE),
        phone=rng.choice(PHONE), rate=rng.choice(["2.9", "3.2", "4.1", "1.8"]), n=n,
        org_ok=rng.choice(["구청", "주민센터", "시청"]),
    )


def build():
    rng = random.Random(SEED)
    rows, seen = [], set()

    def add(kind, label, text):
        if text in seen:
            return
        seen.add(text)
        rows.append({"id": f"sms_{len(rows):04d}", "kind": kind, "label": label, "text": text})

    # 틀마다 4번 채워 변형을 만든다. 같은 틀에서 나온 문장이 학습과 검증에 나뉘어 들어가므로
    # 검증 점수는 "틀을 외웠는가"에 가깝다 — 그래서 진짜 평가는 eval/sms_cases.jsonl 로 한다.
    for kind, temps in POS.items():
        for t in temps:
            for _ in range(4):
                add(kind, 1, fill(t, rng))
    # 정상 틀은 수가 적어 6번 채운다 — 사기 틀이 많아 그대로 두면 사기 64% 로 기운다.
    for kind, temps in NEG.items():
        for t in temps:
            for _ in range(6):
                add(kind, 0, fill(t, rng))

    # 결합 표본. 앞 조각 + 뒤 조각을 채널 표시와 함께 잇는다.
    pre_v = POS["앞 조각(통화)"]; pre_s = POS["앞 조각(문자)"]
    follow = [t for k in ("택배 반송/주소 확인", "명의도용/대출 확인", "대출 광고/앱 설치", "가족/지인 사칭") for t in POS[k]]
    for _ in range(40):
        a = fill(rng.choice(pre_v), rng); b = fill(rng.choice(follow), rng)
        add("결합(사기)", 1, joined("통화", a, "문자", b))
        a = fill(rng.choice(pre_s), rng); b = fill(rng.choice(pre_v), rng)
        add("결합(사기)", 1, joined("문자", a, "통화", b))
    ok_s = [t for k in ("택배 안내", "카드/은행 정상", "쇼핑/주문/예약") for t in NEG[k] if not t.startswith("여보세요") and not t.startswith("안녕하세요 고객님")]
    ok_v = [t for t in NEG["지인 대화"] + NEG["카드/은행 정상"] if t.startswith("여보세요") or t.startswith("안녕하세요 고객님")]
    for _ in range(40):
        a = fill(rng.choice(ok_s), rng); b = fill(rng.choice(ok_v), rng)
        add("결합(정상)", 0, joined("문자", a, "통화", b))
    return rows


def split(rows):
    """층화 분할 — 라벨·유형별로 따로 섞어 나눈다. 검증셋 비율이 우연에 맡겨지면 온도가 휜다."""
    rng = random.Random(SEED)
    train, val = [], []
    kinds = sorted({r["kind"] for r in rows})
    for kind in kinds:
        part = [r for r in rows if r["kind"] == kind]
        rng.shuffle(part)
        cut = int(round(len(part) * (1 - VAL_RATIO)))
        train += part[:cut]
        val += part[cut:]
    rng.shuffle(train)
    rng.shuffle(val)
    return train, val


def report(name, part):
    pos = sum(r["label"] for r in part)
    print(f"{name:6} {len(part):5}건   사기 {pos:4} ({pos/len(part)*100:.1f}%)")
    kinds = {}
    for r in part:
        kinds[r["kind"]] = kinds.get(r["kind"], 0) + 1
    for k, v in sorted(kinds.items(), key=lambda kv: -kv[1]):
        print(f"         {k:18} {v:4}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--stats", action="store_true")
    args = parser.parse_args()

    rows = build()
    train, val = split(rows)
    report("train", train)
    report("val", val)
    if args.stats:
        raise SystemExit
    OUT_DIR.mkdir(exist_ok=True)
    for name, part in (("sms_train", train), ("sms_val", val)):
        path = OUT_DIR / f"{name}.jsonl"
        with path.open("w", encoding="utf-8") as f:
            for r in part:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"→ {path}")
